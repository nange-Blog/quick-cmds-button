const dicts: Record<string, Dict> = { en, zh, cs, sk, de }

let config: ConfigService | null = null

/** Remember Tabby's config so the UI language can follow its language setting. */
export function initI18n (c: ConfigService): void {
    config = c
}

function currentLang (): string {
    const raw: string = config?.store?.language || (typeof navigator !== 'undefined' ? navigator.language : '') || 'en'
    const lang = raw.toLowerCase().split(/[-_]/)[0]
    return dicts[lang] ? lang : 'en'
}

/** Translate a key; `{0}`, `{1}`… are replaced by args. Falls back to English. */
export function t (key: string, ...args: string[]): string {
    const s = dicts[currentLang()][key] ?? en[key] ?? key
    return s.replace(/\{(\d+)\}/g, (_, i) => args[+i] ?? '')
}
